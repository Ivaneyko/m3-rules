#!/usr/bin/env node
// Downloads every generated Material 3 component token file (`*Tokens.kt`) from androidx into
// sources/tokens/components/, unchanged, and writes sources/tokens/component-tokens.md: one table
// per file with every token and its value (sizes, shapes, elevation levels, opacities, colour and
// type roles). m3.material.io shows many component measurements only in pictures; these files are
// the same md.comp.* tokens as text.
//
// Both Kotlin forms are read: `val X = 40.0.dp` and `inline val X: Dp \n get() = 40.0.dp`.
// The system token files (type scale, shape, motion…) are in sources/tokens/base/
// (scripts/refresh-base-tokens.mjs) and are skipped here.
//
//   node scripts/refresh-tokens.mjs        (uses `gh api` to list the folder when gh is signed in)
import { execFileSync } from 'node:child_process';
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = 'compose/material3/material3/src/commonMain/kotlin/androidx/compose/material3/tokens';
const RAW = `https://raw.githubusercontent.com/androidx/androidx/androidx-main/${DIR}/`;
const LIST = `repos/androidx/androidx/contents/${DIR}?ref=androidx-main`;
const BASE = new Set([
  'TypeScaleTokens.kt', 'TypographyKeyTokens.kt', 'TypefaceTokens.kt', 'ShapeTokens.kt',
  'ElevationTokens.kt', 'MotionTokens.kt', 'StandardMotionTokens.kt', 'ExpressiveMotionTokens.kt',
  'StateTokens.kt', 'ColorSchemeKeyTokens.kt'
]);
// Raw palettes and colour schemes: colour values, not component tokens.
const SKIP = new Set([
  'ColorDarkTokens.kt', 'ColorLightTokens.kt', 'PaletteTokens.kt', 'ShapeKeyTokens.kt',
  'MotionSchemeKeyTokens.kt'
]);

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'sources', 'tokens');
const outDir = join(root, 'components');

async function listFiles() {
  let json;
  try {
    json = execFileSync('gh', ['api', LIST], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
  } catch {
    const res = await fetch(`https://api.github.com/${LIST}`);
    if (!res.ok) throw new Error(`listing the token folder: HTTP ${res.status}`);
    json = await res.text();
  }
  return JSON.parse(json)
    .map((f) => f.name)
    .filter((n) => n.endsWith('Tokens.kt') && !BASE.has(n) && !SKIP.has(n))
    .sort();
}

function parse(text) {
  const tokens = [];
  const re = /val\s+(\w+)\s*(?::[^\n=]*)?(?:=\s*([^\n]+)|\n\s*get\(\)\s*=\s*([^\n]+))/g;
  for (const m of text.matchAll(re)) {
    const value = (m[2] ?? m[3]).trim().replace(/\s+/g, ' ');
    tokens.push([m[1], value]);
  }
  return tokens;
}

const files = await listFiles();
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const out = [
  '# Component tokens',
  '',
  'Every token of every generated Material 3 component token file in androidx, as written there',
  '(`androidx-main`, `compose/material3/…/tokens/`). Generated by `scripts/refresh-tokens.mjs`; the',
  'raw files are in `components/`. Values: `40.0.dp` = 40px on the web; `ShapeKeyTokens.CornerMedium`',
  'and the other shape steps resolve with `base/ShapeTokens.kt`; `ElevationTokens.Level1` with',
  '`base/ElevationTokens.kt`; `ColorSchemeKeyTokens.X` is the colour role X; `TypographyKeyTokens.X`',
  'the type style X. A file\'s `VERSION` line says which token set it was generated from.',
  ''
];
let failed = 0;
for (const name of files) {
  const res = await fetch(RAW + name);
  if (!res.ok) {
    console.error(`${name}: HTTP ${res.status}`);
    failed++;
    continue;
  }
  const text = await res.text();
  writeFileSync(join(outDir, name), text);
  const version = text.match(/VERSION:\s*(\S+)/)?.[1] ?? '?';
  out.push(`## ${name.replace(/\.kt$/, '')}`, '', `Version ${version}.`, '', '| Token | Value |', '| --- | --- |');
  for (const [k, v] of parse(text)) out.push(`| \`${k}\` | \`${v}\` |`);
  out.push('');
}
writeFileSync(join(root, 'component-tokens.md'), out.join('\n'));
console.log(`wrote ${files.length - failed} token files to sources/tokens/components/ and component-tokens.md`);
if (failed) process.exit(1);
console.log(readdirSync(outDir).length, 'files');
